// Helper to attach authors, publishers, and categories to books and products
export function getEnrichedBooks(): Book[] {
  return SEED_BOOKS.map((item) => {
    const author = item.author_id
      ? SEED_AUTHORS.find((a) => a.id === item.author_id)
      : undefined;
    const publisher = item.publisher_id
      ? SEED_PUBLISHERS.find((p) => p.id === item.publisher_id)
      : undefined;

    // Default department to 'books' if not set
    const department: Department = item.department || 'books';

    // Find corresponding category based on slug / department
    const categories: Category[] = SEED_CATEGORIES.filter((c) => {
      if (item.department && c.department === item.department) {
        return true;
      }
      return false;
    }).slice(0, 2);

    return {
      ...item,
      department,
      author,
      publisher,
      categories: categories.length > 0 ? categories : [SEED_CATEGORIES[0]],
    };
  });
}
